/** Day of year, 1 January = 1. Day 366 repeats day 365. */
export function dayOfYear(date: Date): number {
  const start = new Date(date.getFullYear(), 0, 0);
  const n = Math.floor((new Date(date.getFullYear(), date.getMonth(), date.getDate()).getTime() - start.getTime()) / 86400000);
  return Math.min(n, 365);
}

export function getDailyEntry(date: Date = new Date()): IChooseEntry {
  return I_CHOOSE_365[dayOfYear(date) - 1];
}
